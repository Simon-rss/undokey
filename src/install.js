import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

export const AGENTS = ["codex", "claude", "opencode", "antigravity"];
const MARK = /undokey(\.js)?["']?\s+hook\s+/;
const BIN = fs.realpathSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "bin", "undokey.js"));

function q(s) {
  return /^[\w@%+=:,./-]+$/.test(s) ? s : `"${s.replace(/(["\\$`])/g, "\\$1")}"`;
}

/** Absolute, stable command line (version managers like fnm/nvm expose per-shell node paths). */
export function hookCommand(agent) {
  let node = process.execPath;
  try {
    node = fs.realpathSync(node);
  } catch {}
  return `${q(node)} ${q(BIN)} hook ${agent}`;
}

function onPath(cmd) {
  return spawnSync("sh", ["-c", `command -v ${cmd}`], { encoding: "utf8" }).status === 0;
}

export function detectAgents() {
  const h = os.homedir();
  return {
    codex: fs.existsSync(path.join(h, ".codex")) || onPath("codex"),
    claude: fs.existsSync(path.join(h, ".claude")) || onPath("claude"),
    opencode: fs.existsSync(path.join(h, ".config", "opencode")) || onPath("opencode"),
    antigravity: fs.existsSync(path.join(h, ".gemini", "config")) || onPath("agy"),
  };
}

/** Where each agent's hook config lives. */
export function targetFile(agent, scope, projectRoot) {
  const h = os.homedir();
  const g = scope === "global";
  switch (agent) {
    case "codex":
      return g ? path.join(h, ".codex", "hooks.json") : path.join(projectRoot, ".codex", "hooks.json");
    case "claude":
      return g ? path.join(h, ".claude", "settings.json") : path.join(projectRoot, ".claude", "settings.local.json");
    case "antigravity":
      return g ? path.join(h, ".gemini", "config", "hooks.json") : path.join(projectRoot, ".agents", "hooks.json");
    case "opencode":
      return g
        ? path.join(h, ".config", "opencode", "plugin", "undokey.js")
        : path.join(projectRoot, ".opencode", "plugin", "undokey.js");
    default:
      throw new Error(`unknown agent ${agent}`);
  }
}

function readJson(file) {
  if (!fs.existsSync(file)) return {};
  const text = fs.readFileSync(file, "utf8");
  if (!text.trim()) return {};
  try {
    return JSON.parse(text);
  } catch (e) {
    throw new Error(`${file} is not valid JSON; not touching it (${/** @type {Error} */ (e).message})`);
  }
}

function writeWithBackup(file, content) {
  const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (old === content) return { changed: false, backup: null };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  let backup = null;
  if (old !== null) {
    backup = `${file}.undokey-${Date.now()}.bak`;
    fs.writeFileSync(backup, old);
  }
  fs.writeFileSync(file, content);
  return { changed: true, backup };
}

const isOurs = (group) => (group?.hooks || [group]).some((h) => typeof h?.command === "string" && MARK.test(h.command));

/** Remove our groups from a Claude/Codex-style `{ Event: [groups] }` map. */
function stripEvents(events) {
  for (const k of Object.keys(events)) {
    if (!Array.isArray(events[k])) continue;
    events[k] = events[k].filter((g) => !isOurs(g));
    if (events[k].length === 0) delete events[k];
  }
}

function claudeStyleGroups(agent, matcherAll) {
  const handler = { type: "command", command: hookCommand(agent), timeout: 30 };
  return {
    UserPromptSubmit: [{ hooks: [handler] }],
    PreToolUse: [{ matcher: matcherAll, hooks: [handler] }],
    PostToolUse: [{ matcher: matcherAll, hooks: [handler] }],
    Stop: [{ hooks: [handler] }],
  };
}

function opencodePlugin() {
  return `// Generated by undokey (https://github.com/Simon-rss/undokey). Remove with: undokey uninstall --agent opencode
import { spawnSync } from "node:child_process";
const CMD = ${JSON.stringify(hookCommand("opencode"))};
const fire = (payload) => {
  try {
    spawnSync(CMD, { shell: true, input: JSON.stringify(payload), timeout: 30000, stdio: ["pipe", "ignore", "ignore"] });
  } catch {}
};
export const Undokey = async ({ directory }) => ({
  "chat.message": async (input) => {
    fire({ hook_event_name: "UserPromptSubmit", session_id: input?.sessionID, turn_id: input?.messageID, cwd: directory });
  },
  "tool.execute.before": async (input) => {
    fire({ hook_event_name: "PreToolUse", tool_name: input?.tool, session_id: input?.sessionID, tool_use_id: input?.callID, cwd: directory });
  },
  "tool.execute.after": async (input) => {
    fire({ hook_event_name: "PostToolUse", tool_name: input?.tool, session_id: input?.sessionID, tool_use_id: input?.callID, cwd: directory });
  },
  event: async ({ event }) => {
    if (event?.type === "session.idle") fire({ hook_event_name: "Stop", session_id: event?.properties?.sessionID, cwd: directory });
  },
});
`;
}

/**
 * @param {string} agent @param {"global"|"project"} scope @param {string} [projectRoot]
 * @returns {{ agent: string, file: string, changed: boolean, backup: string|null, note?: string }}
 */
export function install(agent, scope, projectRoot) {
  const file = targetFile(agent, scope, projectRoot);
  if (agent === "opencode") {
    return { agent, file, ...writeWithBackup(file, opencodePlugin()) };
  }
  const cfg = readJson(file);
  if (agent === "antigravity") {
    cfg.undokey = {
      PreInvocation: [{ type: "command", command: hookCommand(agent), timeout: 30 }],
      PostToolUse: [{ matcher: "*", hooks: [{ type: "command", command: hookCommand(agent), timeout: 30 }] }],
      Stop: [{ type: "command", command: hookCommand(agent), timeout: 30 }],
    };
    return { agent, file, ...writeWithBackup(file, JSON.stringify(cfg, null, 2) + "\n") };
  }
  // codex: hooks.json is either { hooks: { Event: [...] } } or { Event: [...] }
  // claude: settings.json with { hooks: { Event: [...] } }
  let events;
  if (agent === "claude" || (cfg.hooks && typeof cfg.hooks === "object") || Object.keys(cfg).length === 0) {
    cfg.hooks = cfg.hooks && typeof cfg.hooks === "object" ? cfg.hooks : {};
    events = cfg.hooks;
  } else {
    events = cfg;
  }
  stripEvents(events);
  const add = claudeStyleGroups(agent, agent === "claude" ? "*" : ".*");
  for (const [k, groups] of Object.entries(add)) events[k] = [...(events[k] || []), ...groups];
  const res = writeWithBackup(file, JSON.stringify(cfg, null, 2) + "\n");
  const note =
    agent === "codex" && res.changed
      ? "Codex asks you to trust new hooks once: open `codex`, run /hooks and approve the undokey entries."
      : undefined;
  return { agent, file, ...res, note };
}

export function uninstall(agent, scope, projectRoot) {
  const file = targetFile(agent, scope, projectRoot);
  if (!fs.existsSync(file)) return { agent, file, changed: false, backup: null };
  if (agent === "opencode") {
    if (!fs.readFileSync(file, "utf8").includes("Generated by undokey")) return { agent, file, changed: false, backup: null };
    fs.rmSync(file);
    return { agent, file, changed: true, backup: null };
  }
  const cfg = readJson(file);
  if (agent === "antigravity") {
    if (!cfg.undokey) return { agent, file, changed: false, backup: null };
    delete cfg.undokey;
  } else {
    const events = cfg.hooks && typeof cfg.hooks === "object" ? cfg.hooks : cfg;
    stripEvents(events);
    if (cfg.hooks && Object.keys(cfg.hooks).length === 0) delete cfg.hooks;
  }
  return { agent, file, ...writeWithBackup(file, JSON.stringify(cfg, null, 2) + "\n") };
}

/** Is undokey installed for this agent+scope? */
export function isInstalled(agent, scope, projectRoot) {
  const file = targetFile(agent, scope, projectRoot);
  if (!fs.existsSync(file)) return false;
  const text = fs.readFileSync(file, "utf8");
  return agent === "opencode" ? text.includes("Generated by undokey") : MARK.test(text);
}
